fn sin_taylor_horner_fm(x: f64, n: u32) -> f64 {
    let mut i = n;
    let x2 = x * x;

    let mut xmm1;
    let mut xmm2;
    let xmm3;
    let x_m128;
    unsafe {
        xmm1 = if n.is_multiple_of(2) {
            _mm_set_sd(-1.0)
        } else {
            _mm_set_sd(1.0)
        };
        xmm3 = _mm_set_sd(1.0);
        x_m128 = _mm_set_sd(x);
    }

    while i > 1 {
        let denominator = ((2 * i - 1) * (2 * i - 2)) as f64;
        unsafe {
            xmm2 = _mm_set_sd(x2 / denominator);
            xmm1 = if i.is_multiple_of(2) {
                _mm_fmadd_sd(xmm1, xmm2, xmm3)
            } else {
                _mm_fmsub_sd(xmm1, xmm2, xmm3)
            };
        }
        i -= 1;
    }
    unsafe {
        xmm1 = _mm_mul_sd(xmm1, x_m128);
        _mm_cvtsd_f64(xmm1)
    }
}

fn sin_taylor_horner(x: f64, n: u32) -> f64 {
    let mut i = n;
    let x2 = x * x;

    let mut taylor = if n.is_multiple_of(2) { -1.0 } else { 1.0 };

    while i > 1 {
        let denominator = ((2 * i - 1) * (2 * i - 2)) as f64;
        taylor *= x2 / denominator;
        taylor += if i.is_multiple_of(2) { 1.0 } else { -1.0 };
        i -= 1;
    }
    taylor *= x;
    taylor
}

fn sin_taylor(x: f64, n: u32) -> f64 {
    let mut i = 1;
    let mut taylor = 0.0;

    while i <= 2 * n {
        // i/2 maps {1,3,5,...} -> {0,1,2,...} so we can check for parity
        if ((i / 2) % 2) == 0 {
            taylor += x.powi(i as i32) / factorial_f64(i);
        } else {
            taylor -= x.powi(i as i32) / factorial_f64(i);
        }
        i += 2;
    }
    taylor
}

fn factorial_f64(n: u32) -> f64 {
    // You can apparently start the range at 2
    // instead of 1. One might expect that this
    // wouldn't work for factorial(1), however,
    // it turns out the product() method gives
    // 1 on an empty iterator, so it works.
    (2..=n).map(|x| x as f64).product()
}

fn get_max_diff_funcs<F, G>(f: F, g: G, rng_min: f64, rng_max: f64, rng_count: u32) -> f64
where
    F: Fn(f64) -> f64,
    G: Fn(f64) -> f64,
{
    let mut max_diff = 0.0;
    for i in 0..rng_count {
        let t_step = i as f64 / (rng_count as f64 - 1.0);
        let input = (1.0 - t_step) * rng_min + t_step * rng_max;
        let diff = (f(input) - g(input)).abs();
        if max_diff < diff {
            max_diff = diff
        }
    }
    max_diff
}

fn sin_quarter(x: f64) -> f64 {
    let half_pi = PI / 2.0;
    let abs_x = x.abs();
    let x_shifted = if abs_x > half_pi { PI - abs_x } else { abs_x };
    const A: f64 =
        -0.3357488673628103541807525733876701910953780492546723687387637750157263772845455;
    const B: f64 = 1.164012859946630796034863328523423717191309716948615456152205566227330270901187;

    let pos_result = A * x_shifted.powi(2) + B * x_shifted;

    if x > 0.0 { pos_result } else { -pos_result }
}

fn sin_half(x: f64) -> f64 {
    if x > 0.0 {
        -4.0 / PI.powi(2) * x.powi(2) + 4.0 / PI * x
    } else {
        // use sin(-x)=sin(x). First term has sign flipped
        // by the above identity. Second term has sign flipped
        // by sin->-sin but it is flipped again by -x->x, so
        // we end up with an identical second term
        4.0 / PI.powi(2) * x.powi(2) + 4.0 / PI * x
    }
}

fn cos_quarter(x: f64) -> f64 {
    sin_quarter(x + PI / 2.0)
}
