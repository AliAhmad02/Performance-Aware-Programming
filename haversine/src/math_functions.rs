pub fn cos_ce(x: f64) -> f64 {
    sin_ce(x + PI / 2.0)
}

pub fn sin_ce(x: f64) -> f64 {
    // Maximum accuracy achieved at order 9
    sin_quarter_from_table(x, SINE_MINIMAX_COEFFS[9])
}

pub fn asin_ce(x: f64) -> f64 {
    // Maximum accuracy achieved at order 16
    asin_from_table(x, ARCSINE_MINIMAX_COEFFS[16])
}

pub fn sqrt_ce(x: f64) -> f64 {
    unsafe {
        let xmm = _mm_set_sd(x);
        let sqrt = _mm_sqrt_sd(xmm, xmm);
        _mm_cvtsd_f64(sqrt)
    }
}

fn asin_from_table(x: f64, coeffs: &[f64]) -> f64 {
    if x > (1.0 / sqrt_ce(2.0)) {
        PI / 2.0 - approx_from_coeff_table(sqrt_ce(1.0 - x * x), coeffs)
    } else {
        approx_from_coeff_table(x, coeffs)
    }
}

fn sin_quarter_from_table(x: f64, coeffs: &[f64]) -> f64 {
    let half_pi = PI / 2.0;
    let abs_x = x.abs();
    let x_shifted = if abs_x > half_pi { PI - abs_x } else { abs_x };
    let pos_result = approx_from_coeff_table(x_shifted, coeffs);

    if x > 0.0 { pos_result } else { -pos_result }
}

fn approx_from_coeff_table(x: f64, coeffs: &[f64]) -> f64 {
    unsafe {
        let n = coeffs.len();
        let x2 = _mm_set_sd(x * x);
        let mut result = _mm_set_sd(coeffs[n - 1]);
        for i in (0..(n - 1)).rev() {
            let coeff = _mm_set_sd(coeffs[i]);
            result = _mm_fmadd_sd(x2, result, coeff);
        }
        _mm_cvtsd_f64(result) * x
    }
}

